    CONSTRAINT PK_NOTICE PRIMARY KEY (NOTICE_ID),
    CONSTRAINT FK_NOTICE_ADMIN FOREIGN KEY (ADMIN_ID) REFERENCES ADMIN (ADMIN_ID),
    CONSTRAINT CK_NOTICE_HIDDEN CHECK (HIDDEN_YN IN ('Y', 'N'))
);

CREATE TABLE MEMBER (
