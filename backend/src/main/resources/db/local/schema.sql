CREATE TABLE ADMIN (
    ADMIN_ID       NUMBER(19)               NOT NULL,
    LOGIN_ID       VARCHAR2(100)            NOT NULL,
    ADMIN_NAME     VARCHAR2(10)             NOT NULL,
    PASSWORD_HASH  VARCHAR2(255)            NOT NULL,
    PHONE_NUMBER   VARCHAR2(20),
    EMAIL          VARCHAR2(254)            NOT NULL,
    ADMIN_ROLE_CODE VARCHAR2(30)            NOT NULL,
    ADMIN_STATUS   VARCHAR2(20)             DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT     TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_ADMIN PRIMARY KEY (ADMIN_ID),
    CONSTRAINT UK_ADMIN_LOGIN_ID UNIQUE (LOGIN_ID),
    CONSTRAINT UK_ADMIN_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_ADMIN_STATUS CHECK (ADMIN_STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE NOTICE (
    NOTICE_ID      NUMBER(19)               NOT NULL,
