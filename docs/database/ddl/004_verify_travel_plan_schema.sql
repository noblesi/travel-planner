    SELECT 'SEQ_PLAN_DAY' FROM DUAL UNION ALL
    SELECT 'SEQ_PLAN_SCHEDULE_ITEM' FROM DUAL UNION ALL
    SELECT 'SEQ_PLAN_INVITATION' FROM DUAL
)
SELECT EXPECTED.SEQUENCE_NAME
  FROM EXPECTED_SEQUENCES EXPECTED
