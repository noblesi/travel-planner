-- Read-only verification. Expected result: every query returns zero rows,
-- except the final SIDO count which must return 17.

SET PAGESIZE 100
SET LINESIZE 200

PROMPT [Missing tables]
WITH EXPECTED_TABLES (TABLE_NAME) AS (
    SELECT 'REGION_MASTER' FROM DUAL UNION ALL
    SELECT 'PLACE_MASTER' FROM DUAL UNION ALL
    SELECT 'TRAVEL_PLAN' FROM DUAL UNION ALL
    SELECT 'PLAN_MEMBER' FROM DUAL UNION ALL
    SELECT 'PLAN_DAY' FROM DUAL UNION ALL
    SELECT 'PLAN_SCHEDULE_ITEM' FROM DUAL UNION ALL
    SELECT 'PLAN_EDIT_OPERATION' FROM DUAL UNION ALL
    SELECT 'PLAN_INVITATION' FROM DUAL
)
SELECT EXPECTED.TABLE_NAME
  FROM EXPECTED_TABLES EXPECTED
 WHERE NOT EXISTS (
       SELECT 1
         FROM USER_TABLES ACTUAL
        WHERE ACTUAL.TABLE_NAME = EXPECTED.TABLE_NAME
 );

PROMPT [Missing sequences]
